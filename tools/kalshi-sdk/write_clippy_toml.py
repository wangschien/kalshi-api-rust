#!/usr/bin/env python3
"""Write crates/kalshi-api/clippy.toml.

Lists Default::default for every generated *Request model so the hand-written
crate cannot fill those structs silently. Also lists blocking calls.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS = ROOT / "crates" / "kalshi-api-openapi" / "src" / "models"
OUT = ROOT / "crates" / "kalshi-api" / "clippy.toml"
STRUCT_RE = re.compile(r"^pub struct (\w+Request)\b", re.M)

BLOCKING = (
    "std::fs::read",
    "std::fs::read_to_string",
    "std::fs::write",
    "std::fs::File::open",
    "std::fs::File::create",
    "std::fs::OpenOptions::open",
    "std::net::TcpStream::connect",
    "std::net::TcpListener::bind",
    "std::net::UdpSocket::bind",
    "std::thread::sleep",
    "std::thread::spawn",
    "futures::executor::block_on",
    "tokio::runtime::Runtime::block_on",
    "tokio::runtime::Handle::block_on",
)


def main() -> int:
    names = []
    for path in sorted(MODELS.glob("*.rs")):
        names.extend(STRUCT_RE.findall(path.read_text()))
    if not names:
        raise SystemExit("no generated request structs")
    lines = [
        "# Generated by tools/kalshi-sdk/write_clippy_toml.py.",
        "# Do not add Default::default for a generated request by hand.",
        "disallowed-methods = [",
    ]
    for path in BLOCKING:
        lines.append(
            '    { path = "%s", reason = "blocking call is not allowed in this crate" },' % path
        )
    for name in names:
        lines.append(
            '    { path = "kalshi_api_openapi::models::%s::default", reason = "build the request through kalshi_api; Default fills side and other fields", allow-invalid = true },'
            % name
        )
    lines.append("]")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(names)} request types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
